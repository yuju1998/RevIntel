import uuid
from pathlib import Path

import pytest
from alembic import command
from alembic.config import Config
from alembic.util import AutogenerateDiffsDetected
from sqlalchemy import Column, Integer, Table

from app.core.config import Settings
from app.db.base import Base

pytestmark = pytest.mark.integration

ALEMBIC_INI = Path(__file__).resolve().parents[3] / "alembic.ini"


@pytest.fixture
def alembic_config(integration_settings: Settings, monkeypatch: pytest.MonkeyPatch) -> Config:
    # env.py reads DatabaseSettings; environment variables take precedence over `.env`.
    monkeypatch.setenv("DATABASE_URL", str(integration_settings.database_url))
    return Config(str(ALEMBIC_INI))


def test_autogenerate_finds_no_differences_without_models(alembic_config: Config) -> None:
    command.check(alembic_config)


def test_autogenerate_compares_base_metadata(alembic_config: Config) -> None:
    table = Table(
        f"alembic_probe_{uuid.uuid4().hex[:12]}",
        Base.metadata,
        Column("id", Integer, primary_key=True),
    )
    try:
        with pytest.raises(AutogenerateDiffsDetected, match=table.name):
            command.check(alembic_config)
    finally:
        Base.metadata.remove(table)
